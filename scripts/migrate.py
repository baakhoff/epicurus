#!/usr/bin/env python3
"""Every schema-migration chore, in one place: baseline, new, check, gate, services.

Schema is Alembic-managed, one migration environment per service (#834, ADR-XXXX). This
script is the only entry point for authoring and verifying those environments — the Taskfile
(`task migrate:new`, `task migrate:check`) and the `migrations` CI job both call it, so the
gate and the developer run the same code.

    uv run python scripts/migrate.py services
        List the services whose schema is migration-managed, and each one's head revision.

    uv run python scripts/migrate.py baseline <service>
        Render `versions/0001_baseline.py` from the service's models. Writes once; refuses to
        overwrite. See `_render_baseline` for why this is safe to do without Postgres.

    uv run python scripts/migrate.py new <service> "<message>"
        Create the next empty revision for hand-writing. *Not* autogenerate — that needs a
        live Postgres holding the previous schema, which the docker-light local setup does not
        have, and a revision guessed against SQLite would render Postgres-wrong DDL. Write the
        `op.*` calls yourself and let `check` below prove they match the models.

    uv run python scripts/migrate.py check [<service> ...] [--url URL]
        Upgrade an empty database to head, then `alembic check`: fail if the models and the
        revisions disagree — i.e. if a model changed and nobody wrote a revision. Defaults to
        a throwaway SQLite file, so it is a second-long local gate; pass `--url` to run it
        against Postgres.

    uv run python scripts/migrate.py gate --url URL
        What CI runs, against real Postgres, for every migration-managed service: the fresh
        install, the drift check, and the pre-Alembic adoption path — each on a database of
        its own. See `_gate_service`.

Services are discovered by glob (`services/*/src/*/migrations/env.py`), never from a list in
this file or in the workflow: a service lane adopts migrations by adding that directory, and
is covered by the gate from that commit on with nothing else to remember.
"""

